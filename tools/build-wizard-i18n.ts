// Builds the Wizard's per-language word lists (wizard/browser/i18n/<code>.js) from the editable
// translation files in wizard/locales/<code>.json. Each file maps the exact English interface text to
// its translation; anything missing simply stays in English.
import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const root = resolve('.');
const localesRoot = join(root, 'wizard', 'locales');
const outputRoot = join(root, 'wizard', 'browser', 'i18n');
await mkdir(outputRoot, { recursive: true });

for (const file of (await readdir(localesRoot)).filter((name) => name.endsWith('.json')).sort()) {
  const code = file.slice(0, -'.json'.length);
  const entries: unknown = JSON.parse(await readFile(join(localesRoot, file), 'utf8'));
  if (entries === null || typeof entries !== 'object' || Array.isArray(entries)) throw new Error(`${file} must be an object.`);
  for (const [english, translated] of Object.entries(entries)) {
    if (typeof translated !== 'string' || translated.trim() === '') throw new Error(`${file}: "${english}" needs a translation.`);
  }
  const body = `// Generated by tools/build-wizard-i18n.ts from wizard/locales/${file}. Edit that file instead.\n`
    + `(window.THSV_WIZARD_STRINGS ??= {})[${JSON.stringify(code)}] = ${JSON.stringify(entries)};\n`;
  await writeFile(join(outputRoot, `${code}.js`), body);
  console.log(`${code}: ${String(Object.keys(entries).length)} strings`);
}
